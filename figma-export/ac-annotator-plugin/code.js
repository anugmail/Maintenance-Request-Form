/* ---------- จับคู่ชื่อเฟรมกับ entry ด้วย "รหัสเฟรม" (เช่น A.4, E.2, B.6) ไม่ใช่ข้อความส่วนท้าย
   เหตุผล: ข้อความสภาพซ้ำกันได้ข้ามกลุ่ม (เช่น "กดบันทึกโดยยังไม่ครบ" มีทั้งใน B.2 ของฟอร์มสร้างแผน
   และ E.3 ของฟอร์ม PO, "บันทึกสำเร็จ" มีทั้ง B.6/C.5/F.4) เทียบด้วยข้อความส่วนท้ายอย่างเดียวจะชนกัน
   ชื่อเฟรมจริงจาก dump เป็นรูปแบบคงที่ "OH2 / <รหัส> · S<n> — <ข้อความสภาพ>" เช่น
   "OH2 / A.4 · หน้ารายการแผน — ค้นหา — ยังไม่มีแผน" หรือ "OH2 / B.6 · S1 — บันทึกสำเร็จ"
   รหัสเฟรมดึงจาก ENTRIES key เองเสมอ (คำแรกก่อนช่องว่าง) ไม่ต้องมีตารางแยกให้ตกไปต่างหาก ---------- */
function lastSegment(name) {
  const parts = (name || '').split('—');
  return parts[parts.length - 1].trim();
}

/** ดึงรหัสเฟรม (เช่น "B.6") จากชื่อเฟรมจริงใน Figma */
function frameCode(name) {
  const m = /\/\s*([A-Za-z]+\.\d+)\s*·/.exec(name || '');
  return m ? m[1] : null;
}

/** ดึงรหัสเฟรมจาก entry key (key ขึ้นต้นด้วยรหัสเสมอ เช่น "B.6 บันทึกสำเร็จ" → "B.6") */
function entryCode(entryKey) {
  const m = /^([A-Za-z]+\.\d+)\s/.exec(entryKey || '');
  return m ? m[1] : null;
}

/** คืน null ถ้าไม่มีอะไรน่าสงสัย หรือคืนข้อความเตือนถ้ารหัสเฟรมไม่ตรงกับ entry ที่เลือก */
function mismatchWarning(nodeName, entryKey) {
  const expect = entryCode(entryKey);
  if (!expect) return null; // entry นี้ยังไม่มีเฟรมจริงให้เทียบ (กำลังโหลด/โหลดไม่สำเร็จ)
  const got = frameCode(nodeName);
  if (got === expect) return null;
  return 'ชื่อเฟรม "' + nodeName + '" มีรหัส "' + (got || '(ไม่มีรหัส)') + '" แต่ entry "' + entryKey + '" คาดว่าควรเป็นรหัส "' + expect + '" — อาจเลือกผิด';
}

/* ---------- auto-match: สร้าง map รหัส → entryKey จาก ENTRIES เองทุกครั้ง (ไม่ต้องมีตารางแยกมาคอยอัปเดต
   เวลาเพิ่ม entry ใหม่) ให้เลือกเฟรมแล้วแปะได้เลยโดยไม่ต้องเปิด dropdown — ใช้ได้เฉพาะ entry ที่มีรหัส
   (ไม่รวม "กำลังโหลด"/"โหลดไม่สำเร็จ" เพราะยังไม่มีเฟรมจริง ไม่มีรหัสให้จับคู่) ---------- */
const CODE_TO_ENTRY = Object.keys(ENTRIES).reduce((m, k) => {
  const c = entryCode(k);
  if (c) m[c] = k;
  return m;
}, {});

/** คืน entryKey ที่ตรงกับรหัสของชื่อเฟรม หรือ null ถ้าไม่มี entry ไหนตรงเลย */
function findEntryForName(nodeName) {
  const c = frameCode(nodeName);
  return c ? (CODE_TO_ENTRY[c] || null) : null;
}

/** สร้างก้อนข้อความ 1 ก้อน วางไว้ทางขวาของ node ที่เลือก (เฟรมหน้าจอกว้าง 1440 — วางข้างแทนใต้ กันซ้อนเฟรมถัดไป) */
async function annotateNode(node, entryKey) {
  const text = ENTRIES[entryKey];
  await figma.loadFontAsync({ family: 'Inter', style: 'Regular' });
  const tag = figma.createText();
  tag.fontName = { family: 'Inter', style: 'Regular' };
  tag.fontSize = FONT_SIZE;
  tag.characters = 'AC: ' + entryKey + '\n\n' + text;
  tag.textAutoResize = 'HEIGHT';
  tag.resize(ANNOT_WIDTH, 40);
  tag.fills = [{ type: 'SOLID', color: { r: 0.1, g: 0.1, b: 0.1 } }];
  figma.currentPage.appendChild(tag);
  const abs = node.absoluteTransform ? { x: node.absoluteTransform[0][2], y: node.absoluteTransform[1][2] } : { x: node.x, y: node.y };
  tag.x = abs.x + (node.width || 0) + 40;
  tag.y = abs.y;
  tag.setPluginData(TAG_KEY, '1');
  return tag;
}

/** ลบป้ายที่ปลั๊กอินนี้แปะไว้ก่อนหน้า (หา node ที่มี TAG_KEY=1 แล้วลบ) — ป้ายอยู่ที่ระดับ page เสมอ */
function clearTags(root) {
  let n = 0;
  const walk = (node) => {
    const kids = (node.children || []).slice();
    for (const c of kids) {
      if (c.getPluginData && c.getPluginData(TAG_KEY) === '1') {
        c.remove();
        n++;
        continue;
      }
      walk(c);
    }
  };
  walk(root);
  return n;
}

/* ---------- ทางเข้าจริงของปลั๊กอิน (ข้ามส่วนนี้เวลารันเทสใน Node) ---------- */
if (typeof figma !== 'undefined' && figma.showUI) {
  figma.showUI(__html__, { width: 420, height: 480 });

  // ส่งชื่อสิ่งที่เลือกอยู่ไปโชว์ใน UI ตลอด — กันกดแปะทั้งที่ไม่รู้ว่ากำลังเลือกเฟรมไหนอยู่
  const sendSelection = () => {
    figma.ui.postMessage({ type: 'selection', names: figma.currentPage.selection.map((n) => n.name) });
  };
  figma.on('selectionchange', sendSelection);

  figma.ui.onmessage = async (msg) => {
    if (msg.type === 'list') {
      figma.ui.postMessage({ type: 'entries', keys: Object.keys(ENTRIES) });
      sendSelection();
    }
    if (msg.type === 'annotate-auto') {
      const sel = figma.currentPage.selection;
      if (!sel.length) {
        figma.ui.postMessage({ type: 'result', ok: false, text: 'ยังไม่ได้เลือกเฟรมในหน้า — เลือกก่อนแล้วกดใหม่' });
        return;
      }
      let created = 0;
      const unmatched = [];
      for (const node of sel) {
        const key = findEntryForName(node.name);
        if (!key) { unmatched.push(node.name); continue; }
        await annotateNode(node, key);
        created++;
      }
      const lines = [];
      if (created) lines.push('แปะ AC ตามชื่อเฟรมอัตโนมัติแล้ว ' + created + ' เฟรม');
      if (unmatched.length) lines.push('หาไม่เจอ ' + unmatched.length + ' เฟรม (ยังไม่มี AC ให้): ' + unmatched.join(' · ') + ' — เลือก entry เองจาก dropdown ด้านล่างแทน');
      figma.ui.postMessage({ type: 'result', ok: created > 0, text: lines.join('\n') });
    }
    if (msg.type === 'annotate') {
      const sel = figma.currentPage.selection;
      if (!sel.length) {
        figma.ui.postMessage({ type: 'result', ok: false, text: 'ยังไม่ได้เลือกเฟรมในหน้า — เลือกก่อนแล้วกดใหม่' });
        return;
      }
      if (!msg.key || !ENTRIES[msg.key]) {
        figma.ui.postMessage({ type: 'result', ok: false, text: 'ยังไม่ได้เลือก AC entry จาก dropdown' });
        return;
      }
      // กันแปะผิด: เช็คชื่อเฟรมกับ entry ที่เลือกก่อนเสมอ เว้นแต่ผู้ใช้กดยืนยันข้ามแล้ว (msg.force)
      if (!msg.force) {
        const warnings = sel.map((n) => mismatchWarning(n.name, msg.key)).filter(Boolean);
        if (warnings.length) {
          figma.ui.postMessage({
            type: 'mismatch',
            text: warnings.join('\n') + '\n\nกดยืนยันถ้าตั้งใจแปะแบบนี้จริง ไม่ใช่กดผิด',
          });
          return;
        }
      }
      let created = 0;
      for (const node of sel) {
        await annotateNode(node, msg.key);
        created++;
      }
      figma.ui.postMessage({
        type: 'result',
        ok: true,
        text: 'แปะ AC "' + msg.key + '" แล้ว ' + created + ' เฟรม',
      });
    }
    if (msg.type === 'clear') {
      const total = clearTags(figma.currentPage);
      figma.ui.postMessage({ type: 'result', ok: true, text: 'ลบป้าย AC ที่แปะไว้แล้ว ' + total + ' ป้าย' });
    }
  };
}

